/** 任务类型的中文标签（三端通用展示） */
export const TASK_TYPE_LABELS: Record<TaskType, string> = {
  generic: "通用任务",
  preset: "预设场景",
  custom: "自定义",
};

export function findPresetSceneByName(name: string): PresetScene | undefined {
  return PRESET_SCENES.find((scene) => scene.name === name);
}

export function findPresetSceneByKey(key: string): PresetScene | undefined {
  return PRESET_SCENES.find((scene) => scene.key === key);
}

/** 供任务创建表单使用的公开目录（不含内部字段差异，可直接序列化） */
export function presetSceneSummaries(): Array<
  Pick<
    PresetScene,
    "key" | "name" | "tagline" | "defaultTitle" | "description" | "requirements" | "qualityNotes"
  >
> {
  return PRESET_SCENES.map((scene) => ({
    key: scene.key,
    name: scene.name,
    tagline: scene.tagline,
    defaultTitle: scene.defaultTitle,
    description: scene.description,
    requirements: scene.requirements,
    qualityNotes: scene.qualityNotes,
  }));
}
