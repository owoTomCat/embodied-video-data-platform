/**
 * 预设任务场景目录（任务类型体系的核心内容）。
 *
 * 任务类型分三类：
 * - generic：通用任务。不绑定具体场景，适合综合类、跨场景或探索性采集，
 *   在任务创建页中作为最显眼的入口展示。
 * - preset：预设场景任务。从本目录选择一个预设场景，自动带出该场景的
 *   默认标题、任务说明、任务要求与质检提示词拼接内容。
 * - custom：自定义任务。管理员手工填写场景名称与要求（全新场景发布时
 *   自动加入标签字典）。
 *
 * 质检提示词的拼接方式（与 docs/quality 一致）：
 *   完整质检提示词 = 通用模板（qwen-video-ai-quality-framework-v2/system.txt）
 *                  + 平台运行时规则快照（服务端锁定）
 *                  + 任务要求区块（提交时锁定的场景描述 / 分条要求 / 质检提示词内容）
 * 每个预设场景的 qualityNotes 即「质检提示词内容」片段，与场景描述、
 * 分条要求一起在任务规范化确认后锁定，供 AI 质检逐条判定任务符合度。
 */

export type TaskType = "generic" | "preset" | "custom";

export type PresetScene = {
  /** 稳定的场景键，仅用于前端选择与匹配，不落库 */
  key: string;
  /** 场景名称（写入 collection_tasks.scene_name，发布时入标签字典） */
  name: string;
  /** 选择卡片上的简短说明 */
  tagline: string;
  /** 选择该场景时自动带出的默认任务标题 */
  defaultTitle: string;
  /** 面向数采人员的任务说明（采集目标、拍摄方式、完成标准与常见误区） */
  description: string;
  /** 分条原始任务要求（保存后经 AI 规范化拆分为 hard/soft） */
  requirements: string[];
  /** 质检提示词拼接内容：场景边界 + 场景特有质检关注点（进入 quality_notes） */
  qualityNotes: string[];
};

